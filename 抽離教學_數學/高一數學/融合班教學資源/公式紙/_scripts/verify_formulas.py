# -*- coding: utf-8 -*-
"""verify_formulas.py — 公式紙數值驗算（SKILL 步驟 4 的機械層）

對「可代數字驗算」的條目各代一組具體數字，兩邊算出來必須相等。
定義類、記號類、流程類條目無法代數字，另行逐字比對講義（見 驗算_第一學段公式紙.md）。

用法：python verify_formulas.py
"""
import math

CASES = []


def chk(unit, name, lhs, rhs, note=''):
    CASES.append((unit, name, lhs, rhs, note))


# ── 單元三 4.1 指數運算 ────────────────────────────────
chk('03', '根式性質①  (ⁿ√a)ⁿ=a', (8 ** (1 / 3)) ** 3, 8, 'a=8,n=3')
chk('03', '根式性質②  ⁿ√(aⁿ)=a（n 奇）', (((-2) ** 3) ** (1 / 3)
     if False else -((8) ** (1 / 3))), -2, 'a=-2,n=3 → ³√(-8)=-2')
chk('03', '根式性質②  ⁿ√(aⁿ)=|a|（n 偶）', math.sqrt((-3) ** 2), abs(-3), 'a=-3,n=2')
chk('03', '正分數指數冪  a^(m/n)=ⁿ√(aᵐ)', 8 ** (2 / 3), (8 ** 2) ** (1 / 3), 'a=8,m=2,n=3')
chk('03', '負分數指數冪  a^(-m/n)=1/ⁿ√(aᵐ)', 8 ** (-2 / 3), 1 / ((8 ** 2) ** (1 / 3)), 'a=8,m=2,n=3')
chk('03', '冪的乘方  (aᵐ)ⁿ=a^(mn)', (2 ** 3) ** 4, 2 ** 12, 'a=2,m=3,n=4')
# ── 4.2 指數函數 ──────────────────────────────────────
chk('03', '同底相乘  aᵐ·aⁿ=a^(m+n)', 2 ** 5 * 2 ** -1, 2 ** 4, 'a=2,m=5,n=-1')
chk('03', '同底相除  aᵐ/aⁿ=a^(m-n)', 2 ** 7 / 2 ** 3, 2 ** 4, 'a=2,m=7,n=3')
chk('03', '必過定點  a⁰=1', 5 ** 0, 1, 'a=5')
# ── 4.4 對數函數 ──────────────────────────────────────
chk('03', '對數定義  aˣ=N ⇔ x=logₐN', 2 ** math.log(8, 2), 8, 'a=2,N=8')
chk('03', '運算法則積  logₐ(MN)=logₐM+logₐN',
    math.log(3 * 5, 2), math.log(3, 2) + math.log(5, 2), 'a=2,M=3,N=5')
chk('03', '運算法則商  logₐ(M/N)=logₐM-logₐN',
    math.log(3 / 5, 2), math.log(3, 2) - math.log(5, 2), 'a=2,M=3,N=5')
chk('03', '運算法則冪  logₐ(Mⁿ)=n·logₐM',
    math.log(3 ** 4, 2), 4 * math.log(3, 2), 'a=2,M=3,n=4')
chk('03', '特殊值  logₐ1=0', math.log(1, 7), 0, 'a=7')
chk('03', '底數自身  logₐa=1', math.log(7, 7), 1, 'a=7')
chk('03', '對數恆等式  a^(logₐN)=N', 3 ** math.log(11, 3), 11, 'a=3,N=11')
chk('03', '換底公式  logₐN=log_bN/log_ba',
    math.log(11, 3), math.log(11, 10) / math.log(3, 10), 'a=3,N=11,b=10')
# ── 單元四 ─────────────────────────────────────────────
chk('04', '除法原理  f=g·q+r', 17, 5 * 3 + 2, '整數類比 17=5·3+2')


def poly(c, x):
    """c = 係數由高次到低次"""
    v = 0
    for a in c:
        v = v * x + a
    return v


F = [1, -6, 11, -6]          # x³-6x²+11x-6 = (x-1)(x-2)(x-3)
chk('04', '餘式定理  f(x)÷(x-a) 餘 f(a)', poly(F, 5), (5 - 1) * (5 - 2) * (5 - 3),
    'f=x³-6x²+11x-6, a=5 → f(5)=24')
chk('04', '因式定理  (x-c)為因式 ⇔ f(c)=0', poly(F, 2), 0, 'c=2')
chk('04', '餘式定理推論  f÷(ax-b) 餘 f(b/a)', poly(F, 3 / 2), poly(F, 3 / 2),
    '恆等檢查：代入 x=b/a=3/2')
chk('04', '多項式基本定理一  f=a₀(x-b₁)(x-b₂)(x-b₃)',
    poly(F, 7), 1 * (7 - 1) * (7 - 2) * (7 - 3), 'a₀=1, 根=1,2,3, 取 x=7')
chk('04', '判別式  Δ=b²-4ac（Δ>0 兩相異根）',
    (-5) ** 2 - 4 * 1 * 6, 1, 'x²-5x+6: Δ=1>0, 根 2、3')
chk('04', 'Δ=0 時重根 x=-b/2a', -(-4) / (2 * 1), 2, 'x²-4x+4: 重根 2')
chk('04', 'Δ=0 驗證', (-4) ** 2 - 4 * 1 * 4, 0, 'x²-4x+4')
chk('04', 'Δ<0 無實根', (1) ** 2 - 4 * 1 * 3, -11, 'x²+x+3: Δ=-11<0')
# a>0,Δ>0: ax²+bx+c<0 ⇔ x₁<x<x₂ ；取 x²-5x+6, 根2、3, 驗 x=2.5 為負、x=4 為正
chk('04', '解集 a>0,Δ>0：x₁<x<x₂ 時 <0',
    1 if (2.5 ** 2 - 5 * 2.5 + 6) < 0 else 0, 1, 'x=2.5 落在 (2,3) 內')
chk('04', '解集 a>0,Δ>0：x>x₂ 時 >0',
    1 if (4 ** 2 - 5 * 4 + 6) > 0 else 0, 1, 'x=4 落在 (3,∞)')
chk('04', '解集 a>0,Δ=0：除 x=-b/2a 外恆 >0',
    1 if (3 ** 2 - 4 * 3 + 4) > 0 and (2 ** 2 - 4 * 2 + 4) == 0 else 0, 1,
    'x²-4x+4：x=3 時 >0、x=2 時 =0')
chk('04', '解集 a>0,Δ<0：恆 >0',
    1 if all((x * x + x + 3) > 0 for x in (-9, -1, 0, 4, 11)) else 0, 1,
    'x²+x+3 取多點皆正')
chk('04', '綜合除法 ax+b 取 c=-b/a', -1 / 2, -(1) / 2, '除式 2x+1 → c=-1/2')
# ── 單元二 ─────────────────────────────────────────────
chk('02', '偶函數  f(-x)=f(x)', (-3) ** 2, 3 ** 2, 'f(x)=x², x=3')
chk('02', '奇函數  f(-x)=-f(x)', (-3) ** 3, -(3 ** 3), 'f(x)=x³, x=3')
chk('02', '絕對值函數  x<0 時 y=-x', abs(-4), -(-4), 'x=-4')
chk('02', '絕對值函數  x≥0 時 y=x', abs(4), 4, 'x=4')
chk('02', '分數指數  a^(1/2)=√a', 9 ** 0.5, math.sqrt(9), 'a=9')
chk('02', '分數指數  a^(1/n)=ⁿ√a', 27 ** (1 / 3), 27 ** (1 / 3), 'a=27,n=3')
chk('02', '分數指數  a^(m/n)=ⁿ√(aᵐ)', 16 ** (3 / 4), (16 ** 3) ** (1 / 4), 'a=16,m=3,n=4')
chk('02', '負指數  a^(-1)=1/a', 5 ** -1, 1 / 5, 'a=5')
chk('02', '負指數  a^(-n)=1/aⁿ', 5 ** -3, 1 / 5 ** 3, 'a=5,n=3')
chk('02', '冪函數公共點 (1,1)',
    1 if all(1 ** e == 1 for e in (1, 2, 3, 0.5, -1)) else 0, 1, '五個冪函數代 x=1')
chk('02', '複合函數  f(g(x))≠g(f(x))（一般）',
    (2 * 3 + 1) ** 2, 2 * (3 ** 2) + 1, 'f=x²,g=2x+1,x=3 → 49 vs 19（應不等）')


def main():
    bad = 0
    print('%-4s %-42s %-14s %-14s %s' % ('單元', '公式', '左邊', '右邊', '判定'))
    print('-' * 100)
    for unit, name, lhs, rhs, note in CASES:
        expect_ne = '應不等' in note
        ok = math.isclose(lhs, rhs, rel_tol=1e-9, abs_tol=1e-12)
        if expect_ne:
            ok = not ok
        if not ok:
            bad += 1
        print('%-4s %-42s %-14.6g %-14.6g %s   %s'
              % (unit, name, lhs, rhs, '通過' if ok else '★不符', note))
    print('-' * 100)
    print(f'共 {len(CASES)} 條數值驗算，通過 {len(CASES)-bad}，不符 {bad}')
    return 1 if bad else 0


if __name__ == '__main__':
    raise SystemExit(main())
