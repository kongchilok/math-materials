// build_L1.js — L1 n 次方根（抽離小組 40 分鐘 · SOIL 融合班 deck）
// 三段式：動機 3 頁｜注意 4–11 頁｜行動 11–12 頁　　轉換點：P8、P11
const path = require('path');
const { Deck } = require('../../../01_集合與常用邏輯用語/教學簡報/_scripts/soil_kit.js');
const { numberLine } = require('./exp_draw.js');

const d = new Deck('n 次方根');

// ── 動機段 ────────────────────────────────────────────────
d.cover({
  title: 'n 次方根',
  subtitle: '高一數學 · 抽離小組 · 第 1 課（40 分鐘）',
  hook: '帶走一句：單數次一個根，雙數次兩個根',
});

d.agenda({
  steps: [
    '邊個數自乘等於 9？',
    '認住 ^{n}√a 三個部分',
    '單數次同雙數次，答案數目唔同',
    '分層練習：揀一層',
  ],
  note: '中間會停兩次，一齊做練習。',
});

d.problem({
  question: '邊個數，自己乘自己等於 9？',
  sub: '好多人即刻答「3」。但係 (−3) × (−3) 都係 9 —— 兩個都啱。',
  caption: '所以要問清楚：開方之後，究竟有幾多個答案？',
  badge: '舉手：幾多個',
});

// ── 注意段 ────────────────────────────────────────────────
d.cra({
  title: 'x^{2} = 9，由圖睇到式',
  star: true,
  concrete: { text: '一塊正方形地磚，\n面積係 9。\n\n每邊幾長？\n\n量返出嚟：3。' },
  rep: {
    // 刻度只留 0：−3 同 3 已經喺 marks 標咗，上下各標一次係視覺雜訊
    draw: numberLine({ from: -5, to: 5, ticks: [0],
      marks: [{ x: -3, open: false, label: '−3' }, { x: 3, open: false, label: '3' }],
      caption: '離 0 一樣咁遠' }),
    text: '兩點，一正一負',
  },
  abstract: { text: 'x^{2} = 9\n\nx = ±3\n\n正嗰個 3 係邊長，\n負嗰個 −3 都啱條式。' },
  takeaway: '實物只要正數；但條方程本身，正負都係解。',
});

d.rows3({
  title: '^{n}√a 三個部分',
  rows: [
    { icon: '√', term: '根號', desc: '成個記號叫「根式」', eg: '讀「開方」' },
    { icon: 'n', term: '根指數', desc: '開幾多次方，寫喺根號左上角', eg: '^{3}√8 → 開 3 次方' },
    { icon: 'a', term: '被開方數', desc: '俾人開嗰個數，收喺根號入面', eg: '^{3}√8 → 被開方數係 8' },
  ],
});

d.compare2({
  title: '單數次 vs 雙數次',
  star: true,
  // 每欄最多 6 行，唔好貪心 —— 收結嘅一句交俾下面個 note 講（見 L10 註）
  left: {
    head: '單數次（n = 3, 5, 7…）',
    lines: [
      'a > 0 → 一個正數',
      '　^{3}√8 = 2',
      '',
      'a < 0 → 一個負數',
      '　^{3}√(−8) = −2',
    ],
  },
  right: {
    head: '雙數次（n = 2, 4, 6…）',
    lines: [
      'a > 0 → 兩個，一正一負',
      '　√9 = ±3',
      '',
      'a < 0 → 冇答案',
      '　√(−9) 唔存在',
    ],
  },
  note: '記法：單數次「一定得一個」，雙數次「有就兩個，冇就冇」。',
});

d.tableSlide({
  title: '五種情況，一次過睇晒',
  star: true,
  headers: ['情況', '有幾多個 n 次方根', '例'],
  colW: [3.6, 4.3, 4.2],
  rows: [
    ['n 單、a > 0', '一個，係正數', '^{3}√8 = 2'],
    ['n 單、a < 0', '一個，係負數', '^{3}√(−8) = −2'],
    ['n 雙、a > 0', '兩個，一正一負', '^{4}√16 = ±2'],
    ['n 雙、a < 0', '冇', '√(−4) 唔存在'],
    ['a = 0', '一個，就係 0', '^{5}√0 = 0'],
  ],
});

d.layered({
  title: '練習一：搵 x',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① x^{2} = 9', '　 n 係＿數，x = ＿', '', '② x^{3} = 8', '　 n 係＿數，x = ＿'] },
    { stars: '★★☆', head: '練習 B', lines: ['① x^{3} = −8', '', '② x^{5} = −1', '', '③ x^{5} = 0'] },
    { stars: '★★★', head: '練習 C', lines: ['① x^{4} = 16', '　 有幾多個答案？', '', '② x^{4} = −16', '　 有冇答案？點解？'] },
  ],
  note: '做得起 A 就跳上 B、C，三層都係問同一件事。',
  badge: '自己揀一層',
});

d.rows3({
  title: '根式兩條性質',
  rows: [
    { icon: '①', term: '開完再乘返', desc: '(^{n}√a)^{n} = a', eg: '(√5)^{2} = 5　　(^{3}√(−5))^{3} = −5' },
    { icon: '②', term: 'n 係單數', desc: '^{n}√(a^{n}) = a　照原本個數', eg: '^{3}√(2^{3}) = 2　　^{5}√((−2)^{5}) = −2' },
    { icon: '③', term: 'n 係雙數', desc: '^{n}√(a^{n}) = |a|　要戴絕對值', eg: '√((−2)^{2}) = |−2| = 2' },
  ],
});

d.compareCards({
  title: '雙數次開方，最易漏咗絕對值',
  cards: [
    { ok: false, text: '√((a − b)^{2}) = a − b', note: '如果 a < b，右邊係負數，但左邊開方一定唔會負' },
    { ok: true, text: '√((a − b)^{2}) = |a − b|', note: '唔知 a 同 b 邊個大，戴住絕對值就穩陣' },
    { ok: false, text: '^{6}√((−8)^{6}) = −8', note: '6 係雙數 → 答案係 |−8| = 8' },
  ],
  badge: '逐張讀一次',
});

// ── 行動段 ────────────────────────────────────────────────
d.layered({
  title: '練習二：用兩條性質',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① (√5)^{2} = ?', '', '② (^{3}√(−5))^{3} = ?'] },
    { stars: '★★☆', head: '練習 B', lines: ['① √((a − b)^{2}) = ?', '', '② ^{4}√(3^{4}) = ?', '', '③ ^{5}√((−2)^{5}) = ?'] },
    { stars: '★★★', head: '練習 C', lines: ['① ^{6}√((−8)^{6}) = −8', '　 呢條錯喺邊？', '', '② 自己作一條', '　 要戴絕對值嘅題。'] },
  ],
  note: '每題都先問一句：n 係單數定雙數？',
  badge: '自己揀一層',
});

d.summary({
  takeaway: '單數次一個根，雙數次兩個根，負數冇雙數次根。',
  lines: [
    '① 開單數次方 → 照原本個數，正負都保留',
    '② 開雙數次方 → 要戴絕對值 |a|',
    '③ 負數冇雙數次方根：冇嘢自乘雙數次會變負',
  ],
});

d.closing({
  title: '下一課：分數指數冪',
  line: '^{3}√(a^{2}) 呢啲根式，其實可以寫成 a 嘅分數次方',
  iep: '教學調整（Accommodation）：本簡報加入數線表徵、符號部件拆解與分層任務，年級學習標準不變。',
});

const out = path.join(__dirname, '..', '簡報_L1_n次方根.pptx');
d.save(out).then(f => console.log('OK →', f, '| slides:', d.n));
