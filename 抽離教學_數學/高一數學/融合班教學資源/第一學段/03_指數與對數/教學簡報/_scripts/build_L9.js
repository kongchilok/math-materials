// build_L9.js — L9 對數方程：轉換、合併、檢驗（抽離小組 40 分鐘 · SOIL 融合班 deck）
// 本課核心係「檢驗」：log_{6}(x−3)+log_{6}(x−2)=1 會解出兩個根、要捨一個，
// 呢個例子專登揀嚟令學生親眼見到唔檢驗嘅後果。
// 三段式：動機 3 頁｜注意 4–9 頁｜行動 10 頁　　轉換點：P7、P10
const path = require('path');
const { Deck } = require('../../../01_集合與常用邏輯用語/教學簡報/_scripts/soil_kit.js');

const d = new Deck('對數方程');

// ── 動機段 ────────────────────────────────────────────────
d.cover({
  title: '對數方程',
  subtitle: '高一數學 · 抽離小組 · 第 9 課（40 分鐘）',
  hook: '帶走一句：解完一定要檢驗，真數必須大過 0',
});

d.agenda({
  steps: [
    'log_{2}(x + 5) = 3 點解？',
    '轉成指數式，就變返普通方程',
    '解完仲有一步：檢驗',
    '分層練習：揀一層',
  ],
  note: '中間會停兩次，一齊做練習。',
});

d.problem({
  question: 'log_{2}(x + 5) = 3，個 x 係幾多？',
  sub: '讀返個問句：2 嘅 3 次方等於 (x + 5)。即係 x + 5 = 8。',
  caption: '所以 x = 3。轉成指數式之後，就變返做普通嘅一次方程。',
  badge: '一齊做',
});

// ── 注意段 ────────────────────────────────────────────────
d.scaffold4({
  title: '解對數方程四步',
  star: true,
  steps: [
    '化成單一個 log：log_{a}(⋯) = b',
    '轉成指數式：(⋯) = a^{b}',
    '解返條普通方程，求出 x',
    '檢驗：代返入去，每個真數都要 > 0',
  ],
  note: '第 4 步唔係額外功夫 —— 冇檢驗，答案未算做完。',
});

d.rows3({
  title: '有幾個 log 嗰陣，先合併',
  rows: [
    { icon: '＋', term: '兩個相加', desc: 'log_{a}M + log_{a}N = log_{a}(MN)', eg: 'log_{6}(x−3) + log_{6}(x−2) = log_{6}((x−3)(x−2))' },
    { icon: '－', term: '兩個相減', desc: 'log_{a}M − log_{a}N = log_{a}(M/N)', eg: 'log_{2}(3x) − log_{2}(x−1) = log_{2}(3x/(x−1))' },
    { icon: '＝', term: '兩邊都係 log', desc: '底數一樣 → 真數一定一樣', eg: 'log_{a}M = log_{a}N　→　M = N' },
  ],
});

d.layered({
  title: '練習一：轉換同合併',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① log_{5}(4x − 3) = 2', '', '② log_{3}(5x − 1) = 1'] },
    { stars: '★★☆', head: '練習 B', lines: ['① log_{3}(2x+1) + log_{3}4 = 3', '', '② log_{5}(10x) − log_{5}2 = 2', '', '③ log(2x + 1) = 2'] },
    { stars: '★★★', head: '練習 C', lines: ['① log_{2}(3x)', '　 − log_{2}(x − 1) = 3', '', '② log_{4}(x+3)', '　 + log_{4}(x−1) = 1'] },
  ],
  note: '每題最後都要寫一行「檢驗」，唔寫當未做完。',
  badge: '自己揀一層',
});

d.tableSlide({
  title: '示範：解出兩個根，要捨一個',
  star: true,
  // tableSlide 嘅 headers 唔經 rt()（soil_kit 淨係對 body cell 做），
  // 所以 `_{}` 標記擺喺表頭會原封不動印出嚟。條式一律擺入 body。
  headers: ['步驟', '寫出嚟'],
  colW: [2.6, 9.5],
  rows: [
    ['題目', 'log_{6}(x − 3) + log_{6}(x − 2) = 1'],
    ['1 合併', 'log_{6}((x − 3)(x − 2)) = 1'],
    ['2 轉指數', '(x − 3)(x − 2) = 6^{1} = 6'],
    ['3 解方程', 'x^{2} − 5x + 6 = 6　→　x(x − 5) = 0　→　x = 0 或 x = 5'],
    ['4 檢驗', 'x = 0：x − 3 = −3 < 0　✗ 捨去'],
    ['', 'x = 5：2 > 0 同 3 > 0　✓ 保留'],
  ],
});

d.compareCards({
  title: '點解一定要檢驗',
  cards: [
    { ok: false, text: '上面條題答 x = 0 同 x = 5', note: 'x = 0 令 log_{6}(−3) 出現，真數變負數 —— 根本冇呢個數' },
    { ok: true, text: '上面條題答 x = 5', note: '兩個真數都 > 0，先算係方程嘅解' },
    { ok: false, text: '解完二次方程就收工', note: '合併 log 嗰陣會「造出」多咗嘅根，唔檢驗就會答錯' },
  ],
  badge: '一齊讀出聲',
});

// ── 行動段 ────────────────────────────────────────────────
d.layered({
  title: '練習二：解埋檢驗',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① log_{2}(x − 1) = 3', '', '② log_{3}(x + 2) = 2', '', '（記得寫檢驗）'] },
    { stars: '★★☆', head: '練習 B', lines: ['① log_{6}(x−3)', '　 + log_{6}(x−2) = 1', '', '② log_{5}(x+2)', '　 + log_{5}(x−2) = 2'] },
    { stars: '★★★', head: '練習 C', lines: ['① log_{3}(x^{2})', '　 − log_{3}x = 2', '', '② log_{9}(x + 5)', '　 = log_{27}64'] },
  ],
  note: '見到答案有兩個，特別要逐個檢驗 —— 通常會捨一個。',
  badge: '自己揀一層',
});

d.summary({
  takeaway: '解完一定要檢驗：每個真數都要大過 0。',
  lines: [
    '① 四步：合併 → 轉指數式 → 解方程 → 檢驗',
    '② 幾個 log 相加變乘、相減變除，先合併成一個',
    '③ 合併會造出多餘嘅根，檢驗就係用嚟捨走佢',
  ],
});

d.closing({
  title: '下一課：換元法',
  line: '當方程同時出現 2^{2x} 同 2^{x}，就要換個變數嚟做',
  iep: '教學調整（Accommodation）：本簡報加入四步框架、捨根示範與分層任務，年級學習標準不變。',
});

const out = path.join(__dirname, '..', '簡報_L9_對數方程.pptx');
d.save(out).then(f => console.log('OK →', f, '| slides:', d.n));
