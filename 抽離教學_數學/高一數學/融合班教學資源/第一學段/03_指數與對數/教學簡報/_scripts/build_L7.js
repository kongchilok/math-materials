const path = require('path');
const { Deck } = require('../../../01_集合與常用邏輯用語/教學簡報/_scripts/soil_kit.js');

const d = new Deck('對數運算法則');

// ── 動機段 ────────────────────────────────────────────────
d.cover({
  title: '對數運算法則',
  subtitle: '高一數學 · 抽離小組 · 第 7 課（40 分鐘）',
  hook: '帶走一句：乘變加、除變減、次方變係數',
});

d.agenda({
  steps: [
    'log_{2}32 唔使死記',
    '三條法則：乘加、除減、次方落嚟',
    '底數帶次方，點算',
    '分層練習：揀一層',
  ],
  note: '中間會停兩次，一齊做練習。',
});

d.problem({
  question: 'log_{2}32 等於幾多？',
  sub: '死記 2^{5} = 32 都得。但如果係 log_{2}(4 × 8) 呢？',
  caption: '4 同 8 你都識，拆開就唔使記 32 —— 呢個就係運算法則嘅用處。',
  badge: '一齊拆',
});

// ── 注意段 ────────────────────────────────────────────────
d.rows3({
  title: '三條法則',
  star: true,
  rows: [
    { icon: '×', term: '乘變加', desc: 'log_{a}(MN) = log_{a}M + log_{a}N', eg: 'log_{2}(4 × 8) = log_{2}4 + log_{2}8 = 2 + 3 = 5' },
    { icon: '÷', term: '除變減', desc: 'log_{a}(M/N) = log_{a}M − log_{a}N', eg: 'log_{3}(27/9) = 3 − 2 = 1' },
    { icon: 'n', term: '次方變係數', desc: 'log_{a}(M^{n}) = n · log_{a}M', eg: 'log_{2}(8^{2}) = 2 · log_{2}8 = 2 × 3 = 6' },
  ],
});

d.tableSlide({
  title: '入面做乜，出嚟就變乜',
  star: true,
  headers: ['log 括號入面', 'log 外面變成', '例'],
  colW: [3.5, 3.6, 5.0],
  rows: [
    ['乘 ×', '加 +', 'log_{2}(4 × 8) = 2 + 3'],
    ['除 ÷', '減 −', 'log_{3}(27 ÷ 9) = 3 − 2'],
    ['次方 ^{n}', '乘落去做係數', 'log_{2}(8^{2}) = 2 × 3'],
    ['開方 √', '變分數係數', 'log_{2}√2 = (1/2) × 1'],
    ['a 嘅 log_{a}N 次方', '淨返 N', '2 嘅 log_{2}7 次方 = 7'],
  ],
});

d.layered({
  title: '練習一：拆開嚟計',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① log_{2}4 + log_{2}8 = ?', '', '② log_{3}27 − log_{3}9 = ?'] },
    { stars: '★★☆', head: '練習 B', lines: ['① log_{2}(4 × 8) = ?', '', '② log_{5}(25/5) = ?', '', '③ log_{2}(2^{5}) = ?'] },
    { stars: '★★★', head: '練習 C', lines: ['① log_{2}√2 = ?', '　（先寫成分數指數）', '', '② 2 嘅 log_{2}7 次方', '　 = ?　講吓點解。'] },
  ],
  note: '先睇括號入面係乘、除定次方，再決定出嚟變咩。',
  badge: '自己揀一層',
});

d.rows3({
  title: '底數帶次方，點算',
  star: true,
  rows: [
    { icon: '①', term: '真數帶次方', desc: 'log_{a}(M^{n}) = n · log_{a}M', eg: '次方由真數跳出嚟，做乘數' },
    // 注意：rt() 嘅 `_{}`／`^{}` 唔食巢狀大括號（[^}]* 會喺第一個 } 斷開），
    // 所以 log_{(a^{n})}M 呢類寫法會爆。一律改用具體數字，順帶好教啲。
    { icon: '②', term: '底數帶次方', desc: 'log_{9}M = (1/2) · log_{3}M', eg: '9 = 3^{2} → 個 2 倒轉，做分母 1/2' },
    { icon: '③', term: '兩邊都有', desc: 'log_{8}27 = (3/3) · log_{2}3 = log_{2}3', eg: '8 = 2^{3}、27 = 3^{3} → 3 做分子，3 做分母' },
  ],
});

d.scaffold4({
  title: '示範：求 log_{2}√2',
  steps: [
    '根式寫成分數指數：√2 = 2^{1/2}',
    '代入：log_{2}√2 = log_{2}(2^{1/2})',
    '次方變係數：= (1/2) · log_{2}2',
    'log_{2}2 = 1，所以答案 = 1/2',
  ],
  note: '見到根號，第一步永遠係轉做分數指數（第 2 課學過）。',
});

d.compareCards({
  title: '全單元最貴嗰個錯',
  cards: [
    { ok: false, text: 'log_{a}(M + N) = log_{a}M + log_{a}N', note: '冇呢條法則。加減喺括號入面，係拆唔開嘅' },
    { ok: true, text: 'log_{a}(M × N) = log_{a}M + log_{a}N', note: '入面要係「乘」，出嚟先變「加」' },
    { ok: false, text: 'log_{2}8 ÷ log_{2}4 = log_{2}2', note: '兩個 log 相除唔可以咁拆；呢度應該係 3 ÷ 2' },
  ],
  badge: '一齊讀出聲',
});

// ── 行動段 ────────────────────────────────────────────────
d.layered({
  title: '練習二：綜合化簡',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① log_{2}(2^{3}) = ?', '', '② log_{7}7 = ?'] },
    { stars: '★★☆', head: '練習 B', lines: ['① log_{3}√3 = ?', '', '② log_{2}12 − log_{2}3 = ?', '', '③ 3 嘅 log_{3}5 次方 = ?'] },
    { stars: '★★★', head: '練習 C', lines: ['① log_{9}25 化成', '　 以 3 為底。', '', '② log_{4}x = log_{16}9，', '　 求 x。'] },
  ],
  note: '底數唔同嗰陣，先統一底數，再比真數。',
  badge: '自己揀一層',
});

