const path = require('path');
const { Deck } = require('../../../01_集合與常用邏輯用語/教學簡報/_scripts/soil_kit.js');
const { expLogSwap } = require('./exp_draw.js');

const d = new Deck('對數的定義');

// ── 動機段 ────────────────────────────────────────────────
d.cover({
  title: '對數的定義',
  subtitle: '高一數學 · 抽離小組 · 第 6 課（40 分鐘）',
  hook: '帶走一句：log 就係問「個指數係幾多」',
});

d.agenda({
  steps: [
    '2^{x} = 5，個 x 係幾多？',
    'log 係一個問句，唔係一個運算',
    '同樣三個數，兩種擺法',
    '分層練習：揀一層',
  ],
  note: '中間會停兩次，一齊做練習。',
});

d.problem({
  question: '2 嘅幾多次方等於 8？',
  sub: '呢條好易：3。但係「2 嘅幾多次方等於 5」呢？搵唔到整數。',
  caption: '答案存在，只係寫唔出 —— 所以要有一個新記號，專門用嚟寫呢個答案。',
  badge: '一齊試吓',
});

// ── 注意段 ────────────────────────────────────────────────
d.figure({
  title: '同樣三個數，兩種擺法',
  star: true,
  draw: expLogSwap({ base: '2', exp: '3', val: '8', caption: '由頭到尾都係呢三個數，冇多冇少' }),
  side: [
    'log 唔係一種計算，',
    '係一個問句：',
    '',
    '「2 嘅幾多次方',
    '　等於 8？」',
    '',
    '答案就係 3。',
  ],
});

d.scaffold4({
  title: '示範：計 log_{2}8',
  star: true,
  steps: [
    '讀返個問句：2 嘅幾多次方等於 8？',
    '寫成方程：2^{x} = 8',
    '兩邊化同底：2^{x} = 2^{3}',
    '比指數：x = 3，所以 log_{2}8 = 3',
  ],
  note: '見到 log 就讀返個問句 —— 唔好淨係盯住個記號。',
});

d.layered({
  title: '練習一：讀個問句出嚟',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① log_{3}9 = ?', '　（3 嘅幾多次方 = 9）', '', '② log_{5}1 = ?'] },
    { stars: '★★☆', head: '練習 B', lines: ['① log_{2}16 = ?', '', '② log_{2}4 + log_{2}8 = ?', '', '③ log_{3}27 − log_{3}9 = ?'] },
    { stars: '★★★', head: '練習 C', lines: ['① 若 log_{a}4 = 2，', '　 求 a。', '', '② log_{2}16 + log_{3}9', '　 − log_{5}25 = ?'] },
  ],
  note: '每題都先講一次個問句，再落筆。',
  badge: '自己揀一層',
});

d.tableSlide({
  title: '互換五個對照',
  star: true,
  headers: ['指數式', '對數式', '讀法'],
  colW: [3.4, 4.0, 4.7],
  rows: [
    ['2^{3} = 8', 'log_{2}8 = 3', '2 嘅 3 次方係 8'],
    ['3^{2} = 9', 'log_{3}9 = 2', '3 嘅 2 次方係 9'],
    ['5^{0} = 1', 'log_{5}1 = 0', '任何數嘅 0 次方都係 1'],
    ['2^{1} = 2', 'log_{2}2 = 1', '自己嘅 1 次方係自己'],
    ['2^{-2} = 1/4', 'log_{2}(1/4) = −2', '答案可以係負數'],
  ],
});

d.compareCards({
  title: '三條界線，唔可以踩',
  cards: [
    { ok: false, text: 'log_{2}(−8) 有答案', note: '真數一定要大過 0：2 嘅任何次方都係正數，變唔到負' },
    { ok: false, text: 'log_{1}8 有答案', note: '底數唔可以係 1：1 嘅幾多次方都係 1，永遠去唔到 8' },
    { ok: true, text: 'log_{a}1 = 0，任何底數都係', note: '因為 a^{0} = 1；答案可以係 0，但真數唔可以係 0' },
  ],
  badge: '一齊讀出聲',
});

// ── 行動段 ────────────────────────────────────────────────
d.layered({
  title: '練習二：兩邊互換',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['寫成對數式：', '', '① 2^{4} = 16', '', '② 3^{3} = 27'] },
    { stars: '★★☆', head: '練習 B', lines: ['寫成指數式：', '', '① log_{5}25 = 2', '', '② log_{2}(1/8) = −3', '', '③ log_{a}N = b'] },
    { stars: '★★★', head: '練習 C', lines: ['① 解 log_{2}(x − 1) = 3', '', '② 點解真數要 > 0？', '　 舉個例講吓', '　 唔跟會點。'] },
  ],
  note: '互換嗰陣，三個數一個都唔可以走漏。',
  badge: '自己揀一層',
});

d.summary({
  takeaway: 'log 就係問「個指數係幾多」。',
  lines: [
    '① a^{b} = N　⟺　log_{a}N = b：同樣三個數，換個位擺',
    '② 底數 a 兩邊都唔郁；指數同真數對調位置',
    '③ 真數一定 > 0；底數要 > 0 而且 ≠ 1',
  ],
});

d.closing({
  title: '下一課：對數運算法則',
  line: 'log_{2}32 唔使死記 —— 可以拆開嚟計',
  iep: '教學調整（Accommodation）：本簡報加入互換對照圖、問句讀法與分層任務，年級學習標準不變。',
});

