// build_L4.js — L4 分段函數（抽離小組 40 分鐘 · SOIL 融合班 deck）
// 三段式：動機 3 頁｜注意 4–11 頁｜行動 12–14 頁　　轉換點：P3、P10、P12
const path = require('path');
const { Deck } = require('../../../01_集合與常用邏輯用語/教學簡報/_scripts/soil_kit.js');
const { axes, numberLine } = require('./fn_draw.js');

const d = new Deck('分段函數');

// ── 動機段 ────────────────────────────────────────────────
d.cover({
  title: '分段函數',
  subtitle: '高一數學 · 抽離小組 · 第 4 課（40 分鐘）',
  hook: '帶走一句：先睇 x 落喺邊一段，再揀嗰段條式',
});

d.agenda({
  steps: [
    '|−3| 同 |3|，邊個大？',
    'y = |x| 點解要分兩段寫',
    '停車場點收費',
    '分層練習：揀一層',
  ],
  note: '中間會停兩次，一齊做練習。',
});

d.problem({
  question: '|−3| 係幾多？|3| 又係幾多？',
  sub: '絕對值 = 喺數線上，離開 0 有幾遠。方向唔計。',
  caption: '兩個都係 3。同一個答案，但一個要加負號先得，一個唔使 —— 呢個就係「要分段」嘅起點。',
  badge: '一齊答',
});

// ── 注意段 ────────────────────────────────────────────────
d.rows3({
  title: '絕對值：三種情況',
  rows: [
    { icon: '+', term: '正數', desc: '絕對值就係佢自己', eg: '|3| = 3　　|7| = 7' },
    { icon: '0', term: '零', desc: '絕對值係 0', eg: '|0| = 0' },
    { icon: '−', term: '負數', desc: '絕對值係佢嘅相反數（加負號）', eg: '|−3| = −(−3) = 3' },
  ],
});

d.figure({
  title: 'y = |x| 嘅圖象：一個 V 字',
  star: true,
  draw: axes({
    xr: [-3.6, 3.6], yr: [-0.6, 3.6], xticks: [-3, -2, -1, 1, 2, 3], yticks: [1, 2, 3],
    curves: [
      { f: (x) => x,  from: 0,  to: 3 },
      { f: (x) => -x, from: -3, to: 0 },
    ],
    labels: [
      { x: 2.35, y: 3.3, text: 'y = x' },
      { x: -2.35, y: 3.3, text: 'y = −x' },
    ],
  }),
  caption: '兩條射線砌成一個 V 字',
  side: [
    'x ≥ 0 嗰邊：',
    '　 y = x',
    '',
    'x < 0 嗰邊：',
    '　 y = −x',
    '',
    '同一個函數，',
    '要兩條式先寫得晒。',
  ],
});

d.rows3({
  title: '咩叫分段函數',
  rows: [
    { icon: '切', term: '切開定義域', desc: '把 x 嘅範圍分成幾段', eg: '例如：x ≥ 0 一段，x < 0 一段' },
    { icon: '式', term: '每段一條式', desc: '唔同段，用唔同條式計', eg: 'x ≥ 0 用 y = x；x < 0 用 y = −x' },
    { icon: '一', term: '但佢係一個函數', desc: '唔係幾個函數黐埋，係一個', eg: '每個 x 依然只配到一個 y' },
  ],
});

d.compareCards({
  title: 'y = |x| 係一個函數，定係兩個？',
  cards: [
    { ok: false, text: '係兩個函數黐埋一齊', note: '如果係兩個，同一個 x 就會有兩個答案 —— 但實情冇' },
    { ok: true,  text: '係一個函數，分兩段寫', note: '分段只係「寫法」上拆開，「函數」本身冇拆開' },
  ],
  badge: '一齊講一次',
});

d.scaffold4({
  title: '分段函數求值：四步',
  steps: [
    '睇清楚個 x 落喺邊一段。',
    '揀返嗰一段對應嗰條式。',
    '代入計出答案。',
    '檢查：答案合唔合理？',
  ],
  note: '第一步做錯，之後三步全部白做 —— 所以要先圈住範圍，再落筆。',
});

d.tableSlide({
  title: '停車場收費：三段',
  headers: ['泊幾耐 t（鐘）', '點收', '條式'],
  colW: [3.0, 4.4, 4.7],
  rows: [
    ['0 < t ≤ 1', '免費', 'y = 0'],
    ['1 < t ≤ 3', '每個鐘 10 元', 'y = 10(t − 1)'],
    ['t > 3', '首 3 鐘 20 元，之後每鐘 15 元', 'y = 20 + 15(t − 3)'],
  ],
});

d.layered({
  title: '練習一：絕對值同分段求值',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① |−7| = ?', '', '② |5| = ?', '', '③ |0| = ?'] },
    { stars: '★★☆', head: '練習 B', lines: ['f(x) = x + 1（x ≥ 0）', '　　　 = −x　　（x < 0）', '', '① f(2) = ?', '', '② f(−3) = ?'] },
    { stars: '★★★', head: '練習 C', lines: ['f(x) 同 B 題一樣。', '', '① 邊啲 x 會令', '　 f(x) = 3？', '', '　 搵晒出嚟。'] },
  ],
  note: 'C 題唔止一個答案 —— 記唔記得第 1 課講過，兩個 x 配同一個 y 係得嘅？',
  badge: '自己揀一層',
});

d.figure({
  title: '示範：泊咗 5 個鐘，幾多錢？',
  star: true,
  draw: numberLine({
    from: 0, to: 6, ticks: [1, 3, 5], band: { from: 3, to: 6 },
    marks: [{ x: 5, open: false, label: 't = 5' }],
    caption: '5 > 3，所以落喺第三段',
  }),
  side: [
    '① 5 > 3 → 第三段',
    '',
    '② y = 20 + 15(t − 3)',
    '',
    '③ y = 20 + 15(5 − 3)',
    '　 = 20 + 30 = 50',
    '',
    '④ 檢查：1–3 鐘 = 2 × 10 = 20',
    '　 3–5 鐘 = 2 × 15 = 30',
    '　 20 + 30 = 50 ✓',
  ],
});

// ── 行動段 ────────────────────────────────────────────────
d.layered({
  title: '練習二：返去停車場',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['① 泊 0.5 個鐘，', '　 要畀幾多錢？', '', '　（睇清楚第一段）'] },
    { stars: '★★☆', head: '練習 B', lines: ['① 泊 2 個鐘，幾多錢？', '', '② 泊 4 個鐘，幾多錢？', '', '　（兩題唔同段）'] },
    { stars: '★★★', head: '練習 C', lines: ['① 有人畀咗 65 元，', '　 佢泊咗幾耐？', '', '　（今次由 y 倒返轉', '　 搵 t）'] },
  ],
  note: '每題都照四步寫：邊一段 → 邊條式 → 代入 → 檢查。',
  badge: '自己揀一層',
});

d.summary({
  takeaway: '先睇 x 落喺邊一段，再揀嗰段條式。',
  lines: [
    '① 分段只係寫法拆開，佢仍然係一個函數',
    '② 每一段都要寫清楚 x 嘅範圍，唔可以漏',
    '③ 計完檢查一次：呢個答案合唔合理？',
  ],
});

d.closing({
  title: '下一課：單調性',
  line: '睇住條線由左行到右 —— 係向上爬，定係向下滑？',
  iep: '教學調整（Accommodation）：本簡報加入數線表徵、步驟卡與分層任務，年級學習標準不變。',
});

const out = path.join(__dirname, '..', '簡報_L4_分段函數.pptx');
d.save(out).then(f => console.log('OK →', f, '| slides:', d.n));
