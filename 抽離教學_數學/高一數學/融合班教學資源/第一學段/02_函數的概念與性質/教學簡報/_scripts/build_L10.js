const { Deck } = require('../../../01_集合與常用邏輯用語/教學簡報/_scripts/soil_kit.js');
const { machineChain } = require('./fn_draw.js');

const d = new Deck('複合函數');

// ── 動機段 ────────────────────────────────────────────────
d.cover({
  title: '複合函數',
  subtitle: '高一數學 · 抽離小組 · 第 10 課（40 分鐘）',
  hook: '帶走一句：把外層每一個 x，整個換成內層',
});

d.agenda({
  steps: [
    '兩台機器串埋一齊',
    '求 f(g(x))：換咗佢就得',
    '順序唔同，答案唔同',
    '分層練習：揀一層',
  ],
  note: '中間會停兩次，一齊做練習。',
});

d.problem({
  question: '一台機器 ×2，另一台 +3。先入邊台，答案會唔會唔同？',
  sub: '入 5：先 ×2 再 +3 得 13；先 +3 再 ×2 得 16。',
  caption: '同樣兩台機，次序調轉，答案就唔同 —— 呢個就係今日最重要嗰件事。',
  badge: '心算 + 舉手',
});

// ── 注意段 ────────────────────────────────────────────────
d.figure({
  title: '兩台機器串埋一齊',
  star: true,
  draw: machineChain({ caption: 'x 先入 g 機，個結果再入 f 機' }),
  side: [
    'x 入內層 g，',
    '出返 g(x)',
    '',
    'g(x) 再入外層 f，',
    '出返 f(g(x))',
    '',
    '入面嗰個＝內層',
    '出面嗰個＝外層',
  ],
});

d.scaffold4({
  title: '求 f(g(x))：四步',
  steps: [
    '認清楚邊個係內層 g、邊個係外層 f。',
    '喺 f(x) 條式度，把每一個 x 整個換成 g(x)。',
    '展開，化簡。',
    '整理成標準樣，再檢查一次。',
  ],
  note: '第二步係成課嘅重點：係「每一個」x 都要換，唔可以淨係換第一個。',
});

d.tableSlide({
  title: '示範：f(x) = x² + 1，g(x) = 2x − 3',
  star: true,
  headers: ['步', '寫乜'],
  colW: [2.2, 9.9],
  rows: [
    ['① 認內外層', '內層 g(x) = 2x − 3；外層 f(x) = x² + 1'],
    ['② 代入', 'f(g(x)) = (2x − 3)² + 1'],
    ['③ 展開', '(2x − 3)² = 4x² − 12x + 9'],
    ['④ 整理', 'f(g(x)) = 4x² − 12x + 9 + 1 = 4x² − 12x + 10'],
  ],
});

d.compareCards({
  title: 'f(g(x)) 同 g(f(x)) 一唔一樣？',
  cards: [
    { ok: false, text: '兩個都係「f 同 g 複合」，所以一樣', note: '調轉次序即係調轉「邊台機先做」—— 答案通常唔同' },
    { ok: true,  text: '要睇清楚邊個喺入面、邊個喺出面', note: '寫 f(g(x)) 嗰陣，g 喺括號入面 → g 係內層，先做' },
  ],
  badge: '一齊講一次',
});

d.layered({
  title: '練習一：求 f(g(x))',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['f(x) = x + 5', 'g(x) = 2x', '', '① f(g(x)) = ?'] },
    { stars: '★★☆', head: '練習 B', lines: ['f(x) = x²', 'g(x) = x + 3', '', '① f(g(x)) = ?', '', '　（記得展開）'] },
    { stars: '★★★', head: '練習 C', lines: ['f(x) = 2x² − 1', 'g(x) = x − 4', '', '① f(g(x)) = ?', '', '　 整理埋佢。'] },
  ],
  note: '每一個 x 都要換，唔好漏。',
  badge: '自己揀一層',
});

d.compare2({
  title: '換個次序，答案唔同',
  star: true,
  left: {
    head: '先 g 後 f：f(g(x))',
    lines: ['f(x) = x²，g(x) = x + 1', '', 'f(g(x)) = (x + 1)²', '', '= x² + 2x + 1'],
  },
  right: {
    head: '先 f 後 g：g(f(x))',
    lines: ['同樣兩條式', '', 'g(f(x)) = x² + 1', '', '（把 g 入面嘅 x', '　換成 x²）'],
  },
  note: 'x² + 2x + 1 唔等於 x² + 1 —— 所以做複合一定要先睇清楚邊個喺入面。',
});

d.tableSlide({
  title: '複合函數嘅定義域',
  headers: ['要求', '點解', '例：f(x) = √x，g(x) = x − 2'],
  colW: [3.0, 4.0, 5.1],
  rows: [
    ['內層算得出', 'g(x) 本身要有得計', 'g(x) = x − 2，任何 x 都得'],
    ['結果入到外層', 'g(x) 要落喺 f 嘅定義域入面', '√ 入面要 ≥ 0 → x − 2 ≥ 0'],
    ['最後答案', '兩個條件夾埋', 'f(g(x)) = √(x − 2)，定義域 x ≥ 2'],
  ],
});

// ── 行動段 ────────────────────────────────────────────────
d.layered({
  title: '練習二：次序同定義域',
  cols: [
    { stars: '★☆☆', head: '練習 A', lines: ['f(x) = x + 1', 'g(x) = 3x', '', '① f(g(x)) = ?', '', '② g(f(x)) = ?'] },
    { stars: '★★☆', head: '練習 B', lines: ['f(x) = √x', 'g(x) = x − 5', '', '① f(g(x)) = ?', '', '② 定義域係乜？'] },
    { stars: '★★★', head: '練習 C', lines: ['f(x) = 1/x', 'g(x) = x + 2', '', '① f(g(x)) = ?', '', '② 定義域係乜？', '　（今次係分母）'] },
  ],
  note: 'A 題兩個答案唔同 —— 寫完自己對一對。',
  badge: '自己揀一層',
});

