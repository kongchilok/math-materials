"""verify_ch5.py — 用 sympy 逐題重算第五章十一份講義練習的答案，並寫出《驗算_第五章_一元一次方程.md》。
每一項＝(課, 題號, 說明, 重算值, 講義答案)；兩者不等就 FAIL 並以非零碼結束。
解方程一律由 sympy 從「原方程」重新解，不抄講義的中間步驟。"""
import io
import os
import sys
from sympy import symbols, Rational as R, Eq, solve, simplify, sympify, expand

if hasattr(sys.stdout, 'buffer'):
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

x, y, t, a, k, m = symbols('x y t a k m')
ROWS = []
BAD = 0


def chk(lesson, no, desc, got, want):
    global BAD
    g, w = sympify(got), sympify(want)
    if hasattr(g, '__len__') or hasattr(w, '__len__'):      # tuple／list：逐項比
        g, w = list(g), list(w)
        ok = len(g) == len(w) and all(
            (simplify(sympify(p) - sympify(q)) == 0) if not hasattr(p, '__len__') else
            all(simplify(sympify(u) - sympify(v)) == 0 for u, v in zip(p, q)) for p, q in zip(g, w))
    else:
        ok = simplify(g - w) == 0
    BAD += (not ok)
    ROWS.append((lesson, str(no), desc, str(got), str(want), 'PASS' if ok else 'FAIL'))


def sv(lesson, no, lhs, rhs, want, var=x, desc=None):
    """由原方程 lhs = rhs 重新解，與講義答案比對；另核講義答案代回左右相等。"""
    s = solve(Eq(lhs, rhs), var)
    got = s[0] if len(s) == 1 else s
    chk(lesson, no, desc or f'{lhs} = {rhs}', got, want)


def same(lesson, no, desc, e1, e2):
    """兩式恆等（去括號、去分母後的式子）。"""
    chk(lesson, no, desc, expand(e1 - e2), 0)


def note(lesson, no, desc, text):
    ROWS.append((lesson, str(no), desc, text, '—', '人工核對'))


