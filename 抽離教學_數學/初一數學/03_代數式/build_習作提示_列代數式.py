def ct(title):
    return para(f'▍{title}', bold=True, sz=HEADING_SZ, spacing=False)


def trig(text):
    return para(f'什麼時候翻我：{text}', sz=20, shd=GREY_FILL, spacing=False)


def vt(text):
    """把大括號外的單一小寫字母（變數）包成 {x}，令它以 OMML 斜體顯示，同式子內一致。"""
    parts = re.split(r'(\{[^{}]*\})', text)
    return ''.join(x if x.startswith('{') else
                   re.sub(r'(?<![A-Za-z0-9./])([a-z])(?![A-Za-z/])', lambda m: '{' + m.group(1) + '}', x)
                   for x in parts)


def cl(text, bold=False):
    return para(vt(text), sz=CARD_SZ, bold=bold, spacing=False)


