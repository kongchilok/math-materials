def hp(text):
    return para(vt(text), sz=23, spacing=False)


def rows(items):
    """items: [(題號, [提示句, ...]), ...] → 兩欄表"""
    out = [{'hdr': True, 'cells': [
        {'p': [para('題號', bold=True, sz=22)], 'shd': GREY_FILL},
        {'p': [para('提示（卡住才看；答案寫在書上）', bold=True, sz=22)], 'shd': GREY_FILL}]}]
    for q, lines in items:
        out.append([[para(q, bold=True)], [hp(x) for x in lines]])
    return _tbl(out, [W1, W2])


