    para('　{a=3}、{b=−6}、{c=3}；{Δ=(−6)^2−4(3)(3)=36−36=0}，故有兩個相等實根。'),
    para('　（另驗：{3x^2−6x+3=3(x−1)^2=0}，重根 {x=1}，與 {Δ=0} 相符。）'),
    para('　誘答 A：漏乘 a，誤算 {Δ=36−4(3)=24>0}。'),
