    para('　去分母（兩邊乘 x）：{5=x(x−4)}'),
    para('　展開：{5=x^2−4x}'),
    para('　移項：{x^2−4x−5=0}'),
    para('　因式分解：{(x−5)(x+1)=0}'),
    para('　分兩支：{x−5=0} 或 {x+1=0}'),
    para('　{x_1=5} 或 {x_2=−1}'),
    para('　驗根：{x_1=5≠0} ✓；{x_2=−1≠0} ✓，兩根都保留。'),
