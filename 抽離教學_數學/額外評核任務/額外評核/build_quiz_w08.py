    para('　移項：{x^2−5x=0}'),
    para('　因式分解：{x(x−5)=0}'),
    para('　分兩支：{x=0} 或 {x−5=0}'),
    para('　{x_1=0} 或 {x_2=5}'),
    para('　驗根（代回原方程）：'),
    para('　　{x=0}：左 {=sqrt(4)=2}，右 {=0−2=−2}，{2≠−2} ✗ 捨去'),
    para('　　{x=5}：左 {=sqrt(9)=3}，右 {=5−2=3} ✓ 保留'),
    para('　∴ {x=5}'),
