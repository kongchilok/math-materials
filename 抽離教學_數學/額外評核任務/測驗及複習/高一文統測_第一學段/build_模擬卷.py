def mc(n, stem, items, work=0, cols=None):
    """選擇題：題幹＋選項表＋（計算題）草稿線。"""
    stem_p = tight(para(f'{n}．{stem}（　　）')).replace('<w:pPr>', '<w:pPr><w:keepNext/>', 1)
