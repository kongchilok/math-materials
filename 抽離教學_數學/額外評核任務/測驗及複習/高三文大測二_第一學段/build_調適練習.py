def fig_sine(path):
    """第 8 題：y＝2 sin ωx＋1 的部份圖像，標出 (0, 1) 與相鄰最高點 (π/6, 3)。
    ω＝3，畫 x 由 −π/12 到 5π/6（多於一個週期 2π/3）。黑白。"""
    if os.path.exists(path):
        return path
    import numpy as np
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    pi = np.pi
    fig, ax = plt.subplots(figsize=(3.4, 2.2), dpi=220)
    xs = np.linspace(-pi / 12, 5 * pi / 6, 400)
    ax.plot(xs, 2 * np.sin(3 * xs) + 1, color='black', lw=1.4)
    ax.axhline(0, color='black', lw=0.9)
    ax.axvline(0, color='black', lw=0.9)
    ax.plot([pi / 6, pi / 6], [0, 3], ls='--', color='#555555', lw=0.8)
    ax.plot([0, pi / 6], [3, 3], ls='--', color='#555555', lw=0.8)
    ax.plot([0, 5 * pi / 6], [1, 1], ls=':', color='#888888', lw=0.8)
    ax.plot([pi / 6], [3], 'o', color='black', ms=3.2)
    ax.plot([0], [1], 'o', color='black', ms=3.2)
    ax.text(pi / 6, -0.25, r'$\frac{\pi}{6}$', ha='center', va='top', fontsize=10)
    ax.text(-0.04, 3, '3', ha='right', va='center', fontsize=9)
    ax.text(-0.04, 1.15, '1', ha='right', va='bottom', fontsize=9)
    ax.text(-0.04, -1, r'$-1$', ha='right', va='center', fontsize=9)
    ax.plot([-0.02, 0.02], [-1, -1], color='black', lw=0.9)
    ax.text(-0.05, -0.12, 'O', ha='right', va='top', fontsize=9, style='italic', family='serif')
    ax.text(5 * pi / 6 + 0.05, -0.1, 'x', fontsize=10, style='italic', family='serif', va='top')
    ax.text(0.05, 3.55, 'y', fontsize=10, style='italic', family='serif')
    ax.set_xlim(-0.35, 5 * pi / 6 + 0.2); ax.set_ylim(-1.5, 3.7)
    ax.axis('off')
    fig.savefig(path, dpi=220, bbox_inches='tight', pad_inches=0.02, facecolor='white')
    plt.close(fig)
    return path


