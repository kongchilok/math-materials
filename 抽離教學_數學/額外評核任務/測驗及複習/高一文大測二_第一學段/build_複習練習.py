def _build(doc, teacher=False):
    if teacher:
        P = [masthead(SUBJ, doc['unit'], doc['type'])] + docx_elems(doc['body'])
        out = os.path.join(HERE, doc['file'] + '.docx')
        build_docx(P, out, footer_text=doc['foot'])
    else:
        out = build_docx_file(doc)
    h = build_html_file(doc)
    if teacher:  # 教師版不要姓名列
        with open(h, encoding='utf-8') as f:
            s = f.read()
        s = re.sub(r'<div class="ws-meta">.*?</div>\n', '', s, count=1, flags=re.S)
        with open(h, 'w', encoding='utf-8') as f:
            f.write(s)
    print(out)
    print(html_to_pdf(h))


