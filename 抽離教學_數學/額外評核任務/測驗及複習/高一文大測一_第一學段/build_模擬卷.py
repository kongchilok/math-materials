def q(text, *extra):
    p = tight(para(text))
    if extra:
        p = p.replace('<w:pPr>', '<w:pPr><w:keepNext/>', 1)
    return [p] + list(extra)


def mc(n, stem, items, work=0, cols=None):
    """選擇題：題幹＋選項表＋（計算題）草稿線。"""
    out = [tight(para(f'{n}．{stem}（　　）')), opts(items, cols=cols)]
    if work:
        out += lines(work)
    return out


def section(t):
    return tight(para([('t', t)], bold=True, sz=HEADING_SZ)).replace('<w:pPr>', '<w:pPr><w:keepNext/>', 1)


