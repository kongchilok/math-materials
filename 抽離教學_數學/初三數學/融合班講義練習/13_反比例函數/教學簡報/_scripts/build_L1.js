// build_L1.js — 初三 13 反比例函數．L1「反比例函數的概念」
// 抽離小組（Accommodation）｜40 分鐘｜Sage Calm 低刺激｜廣東話口語
// 共用底層：高一 01 單元 soil_kit.js（唯一一份，唔複製）
const path = require('path');
const KIT = require('../../../../../高一數學/融合班教學資源/第一學段/01_集合與常用邏輯用語/教學簡報/_scripts/soil_kit.js');
const { Deck, C, F, drawEq } = KIT;

const d = new Deck('L1　反比例函數的概念', '初三數學');

// ── 1 封面 ────────────────────────────────────────────────
d.cover({
  title: '反比例函數\n係咩嚟㗎？',
  subtitle: 'L1　反比例函數的概念',
  hook: '由 12 粒糖講起',
});

// ── 2 流程預告頁（ASD 可預測性）──────────────────────────
d.agenda({
  steps: [
    '數糖仔：12 粒點樣分？',
    '認識 y ＝ k/x 呢個樣',
    '一齊判斷：邊條係反比例函數',
    '揀一層，自己做做看',
  ],
  note: '今日唔使計好難嘅嘢，識得「認得出」就夠。',
});

// ── 3 問題引入（保底成功經驗：人人做得起）──────────────
d.problem({
  title: '先想一想',
  question: '12 粒糖，平均分俾 x 個人，每人分到 y 粒。',
  // sub 最多兩行（problem() 嘅 sub 區高 0.9"，23pt 放唔落第三行，會被灰框切底）
  sub: '2 個人　→　每人 6 粒\n3 個人　→　每人 4 粒',
  caption: '你發現咩？　人數 × 每人粒數 ＝ 12，次次都係 12。',
  badge: '一齊數：4 個人、6 個人嘅話呢？',
});

// ── 4 CRA 三階（具體 → 表徵 → 抽象）────────────────────
d.cra({
  title: '由糖仔去到算式',
  concrete: { text: '12 粒糖\n\n分俾 x 個人\n\n每人 y 粒' },
  rep:      { text: 'x ＝ 2　→　y ＝ 6\n\nx ＝ 3　→　y ＝ 4\n\nx ＝ 4　→　y ＝ 3\n\nx ＝ 6　→　y ＝ 2' },
  abstract: { draw: drawEq(['y ＝ ', { n: '12', d: 'x' }], { size: 40 }),
              text: '由 xy ＝ 12 得出' },
  takeaway: '人數大咗，每人分到就細咗——但相乘永遠係 12',
});

// ── 5 定義：睇三樣嘢 ──────────────────────────────────
d.rows3({
  title: '反比例函數：睇三樣嘢',
  rows: [
    { icon: '1', term: 'x 喺下面', desc: 'x 一定要喺分數線下面',
      eg: '寫成 xy ＝ k 都係同一件事' },
    { icon: '2', term: 'k 係常數', desc: '上面嗰個係一個固定嘅數',
      eg: '正數負數都得，例如 12、−8' },
    { icon: '3', term: 'k ≠ 0', desc: 'k 唔可以係 0',
      eg: '點解？一陣會拆開講' },
  ],
  badge: '一陣一齊判斷 4 條式',
});

// ── 6 兩種寫法（同一件事）──────────────────────────────
const twoForms = (s, x, y, w, h) => {
  drawEq(['y ＝ ', { n: 'k', d: 'x' }], { size: 46 })(s, x, y, w, h * 0.40);
  s.addText('兩邊同時乘 x', { x, y: y + h * 0.42, w, h: 0.40, fontFace: F,
    fontSize: 19, color: C.MUTED2, align: 'center', valign: 'middle', margin: 0 });
  drawEq(['xy ＝ k'], { size: 46 })(s, x, y + h * 0.55, w, h * 0.40);
};
d.figure({
  title: '同一件事，兩種寫法',
  draw: twoForms,
  caption: '兩種寫法，同一個反比例函數',
  side: ['見到邊一種寫法，', '都係反比例函數。', '', 'k 係上面嗰個常數，', 'x 一定要喺下面。'],
});

// ── 7 迷思澄清：邊條係反比例函數 ──────────────────────
d.eqJudge({
  title: '呢啲係唔係反比例函數？',
  rows: [
    { parts: ['y ＝ ', { n: '5', d: 'x' }],  ok: true,
      note: 'x 喺分數線下面，上面係常數 5　→　k ＝ 5' },
    { parts: ['y ＝ ', { n: 'x', d: '5' }],  ok: false,
      note: 'x 走咗去上面！分數線下面係 5，唔係 x' },
    { parts: ['y ＝ ', { n: '−7', d: 'x' }], ok: true,
      note: 'k 係負數都得，−7 都係一個常數' },
    { parts: ['y ＝ 3x ＋ 1'],               ok: false,
      note: '冇分數線，x 喺上面——呢個係一次函數' },
  ],
});

// ── 8 步驟卡（一步一行，之後練習沿用）──────────────────
d.scaffold4({
  title: '判斷四步',
  steps: [
    '睇 x 喺邊：喺分數線下面嗎？',
    '睇上面：係唔係一個固定嘅數？',
    '問一句：呢個數係咪 0？',
    '講出 k：上面嗰個數就係 k',
  ],
  note: '四步做完，就答得出「係」定「唔係」，同埋 k 等於幾多。',
});

// ── 9 一齊做（示範 → 引導 → 學生做）────────────────────
d.tableSlide({
  title: '用四步，逐條判',
  headers: ['式', 'x 喺下面？', '係反比例？', 'k ＝'],
  rows: [
    ['y ＝ 8/x',  '✓ 係',             '✓ 係',   '8'],
    ['y ＝ x/8',  '✗ 唔係',           '✗ 唔係', '—'],
    ['y ＝ −2/x', '✓ 係',             '✓ 係',   '−2'],
    ['xy ＝ 10',  '改寫成 y ＝ 10/x', '✓ 係',   '10'],
  ],
  colW: [3.0, 3.4, 2.7, 3.0],
  badge: '下一頁：自己揀一層做',
});

// ── 10 迷思澄清：點解 k 唔可以係 0 ────────────────────
d.problem({
  title: '點解 k 唔可以係 0？',
  question: '如果 k ＝ 0，會變成點？',
  sub: 'y ＝ 0/x ＝ 0\n\n無論 x 係幾多，y 都一律係 0。',
  caption: '咁就變咗一條打橫線，唔再係雙曲線——所以定義寫明 k ≠ 0。',
});

// ── 11 分層任務（同一頁、自選晉級）──────────────────────
d.layered({
  cols: [
    { stars: '★☆☆', head: '練習 A',
      lines: ['圈出反比例函數：', '', 'y ＝ 4/x', 'y ＝ 4x', 'y ＝ −4/x', '', '再寫低每個 k。'] },
    { stars: '★★☆', head: '練習 B',
      lines: ['(1) y ＝ 10/x', '　　k ＝ ？', '', '(2) 把 xy ＝ 15', '　　改寫成', '　　y ＝ ?/x'] },
    { stars: '★★★', head: '練習 C',
      lines: ['y ＝ (k − 2)/x', '係反比例函數。', '', 'k 可以係咩數？', '', '提示：k − 2 ≠ 0'] },
  ],
  note: '做完一層想試上一層，隨時可以。',
});

// ── 12 總結 ──────────────────────────────────────────
d.summary({
  takeaway: 'x 同 y 相乘永遠係 k，一個大、另一個就細',
  lines: [
    '1　x 一定要喺分數線下面',
    '2　上面嗰個常數就係 k',
    '3　k 唔可以係 0',
  ],
});

// ── 13 收結 ──────────────────────────────────────────
d.closing({
  title: 'L1 完成',
  line: '下一課：畫出反比例函數嘅圖像',
  iep: '本課為調整支援（Accommodation）：年級標準不變，只調整呈現方式與練習層次。',
});

d.save(path.join(__dirname, '..', '簡報_L1_反比例函數的概念.pptx'))
  .then((f) => console.log('OK', f));
