// build_L3.js — 初三 13 反比例函數．L3「增減性與中心對稱」
// 本課核心 = 全單元最大陷阱：「每一支上」四個字唔可以漏，跨支唔可以比。
const path = require('path');
const { KIT, hyperbola } = require('./inv_draw.js');
const { Deck } = KIT;

const d = new Deck('L3　增減性與中心對稱', '初三數學');

d.cover({
  title: '喺同一支上面\ny 係點變？',
  subtitle: 'L3　增減性與中心對稱',
  hook: '四個字好緊要：每一支上',
});

d.agenda({
  steps: [
    '喺一支上面行，y 點變？',
    'k ＞ 0 同 k ＜ 0 有咩唔同',
    '陷阱：跨支比較唔算數',
    '揀一層，自己做做看',
  ],
  note: '今日最重要係學識講齊「每一支上」四個字。',
});

// ── 引入：沿住第一象限嗰支行 ────────────────────────
d.problem({
  title: '沿住一支行落去',
  question: '喺 y ＝ 12/x 第一象限嗰支上面行：',
  sub: 'x：　2　→　3　→　4　→　6\ny：　6　→　4　→　3　→　2',
  caption: 'x 越行越大，y 就越嚟越細。',
  badge: '一齊講：x 再大落去，y 會點？',
});

d.figure({
  title: 'k ＞ 0：每一支都向下行',
  draw: hyperbola(12, { pts: [{ x: 2, y: 6 }, { x: 3, y: 4 }, { x: 4, y: 3 }, { x: 6, y: 2 }] }),
  caption: 'y ＝ 12/x：兩支都係越向右越低',
  side: ['喺同一支上面，', 'x 由 2 行到 6，', 'y 由 6 跌到 2。', '', '→ y 隨 x 增大而減小'],
});

d.tableSlide({
  title: 'k ＞ 0：兩支各自睇',
  headers: ['邊一支', 'x 由細到大', 'y 點變'],
  rows: [
    ['第一象限', '2 → 3 → 4 → 6', '6 → 4 → 3 → 2　（減小）'],
    ['第三象限', '−6 → −4 → −3 → −2', '−2 → −3 → −4 → −6　（減小）'],
  ],
  colW: [2.6, 4.2, 5.3],
  badge: '下一頁：k 變負數會點？',
});

d.figure({
  title: 'k ＜ 0：每一支都向上行',
  draw: hyperbola(-12, { pts: [{ x: -6, y: 2 }, { x: -3, y: 4 }, { x: 3, y: -4 }, { x: 6, y: -2 }] }),
  caption: 'y ＝ −12/x：兩支都係越向右越高',
  side: ['k ＜ 0 嘅時候，', '喺同一支上面', 'x 越大，', 'y 都跟住越大。', '', '→ y 隨 x 增大而增大'],
});

d.compare2({
  title: '兩種情況，一句記住',
  left:  { head: 'k ＞ 0', lines: ['例：y ＝ 12/x', '', '第一、三象限', '', '每一支上：', 'y 隨 x 增大而減小'] },
  right: { head: 'k ＜ 0', lines: ['例：y ＝ −12/x', '', '第二、四象限', '', '每一支上：', 'y 隨 x 增大而增大'] },
  note: '兩邊都要講齊「每一支上」——下一頁講點解。',
});

// ── 陷阱頁（本單元最易錯）─────────────────────────────
d.problem({
  title: '陷阱：唔可以跨支比',
  question: '喺 y ＝ 12/x 上面，睇 (−2, −6) 同 (2, 6)：',
  sub: 'x：　−2　→　2　（增大咗）\ny：　−6　→　6　（都增大咗）',
  caption: '咁係咪「y 隨 x 增大而增大」？唔係——呢兩點唔喺同一支，比唔到。',
});

d.compareCards({
  title: '講法啱唔啱？',
  cards: [
    { ok: false, text: 'y ＝ 12/x：y 隨 x 增大而減小',
      note: '漏咗「每一支上」四個字，跨支就唔成立' },
    { ok: true,  text: 'y ＝ 12/x：每一支上，y 隨 x 增大而減小',
      note: '講齊四個字，先至啱' },
    { ok: false, text: '(−2, −6) 同 (2, 6) 比：y 增大咗',
      note: '兩點分別喺第三、第一象限，唔同支，比唔到' },
  ],
});

d.figure({
  title: '兩支之間嘅關係',
  draw: hyperbola(12, {
    pts: [{ x: 3, y: 4 }, { x: -3, y: -4 }],
    segs: [{ x1: -5.5, y1: -7.33, x2: 5.5, y2: 7.33, dash: true, head: false }],
  }),
  caption: '(3, 4) 同 (−3, −4)：關於原點對稱',
  side: ['喺一支上面搵一點，', '過原點畫一條直線，', '', '另一邊嗰支', '一定有對應嘅點。', '', '呢個叫中心對稱。'],
});

d.scaffold4({
  title: '判斷增減四步',
  steps: [
    '搵出 k：分數線上面嗰個數',
    'k ＞ 0：每一支上，y 隨 x 增大而減小',
    'k ＜ 0：每一支上，y 隨 x 增大而增大',
    '答嘅時候，一定要講「每一支上」',
  ],
  note: '第四步唔係客氣說話——漏咗就錯。',
  badge: '下一頁：自己揀一層做',
});

d.layered({
  cols: [
    { stars: '★☆☆', head: '練習 A',
      lines: ['y ＝ 3/x', '', '(1) k 係正定負？', '', '(2) 每一支上，', '　　y 隨 x 增大', '　　而＿＿？'] },
    { stars: '★★☆', head: '練習 B',
      lines: ['y ＝ −9/x', '', '(1) k ＝ ？', '(2) 喺第幾象限？', '(3) 每一支上，', '　　y 隨 x 增大', '　　而＿＿？'] },
    { stars: '★★★', head: '練習 C',
      lines: ['小明話：「y ＝ 5/x', '入面 x 越大 y 越細，', '所以 (−1, −5) 嘅 y', '細過 (1, 5) 嘅 y。」', '', '佢個結論啱唔啱？', '佢個理由啱唔啱？'] },
  ],
  note: '練習 C 要分開睇「結論」同「理由」。',
});

d.summary({
  takeaway: '講增減，一定要先講「每一支上」',
  lines: [
    '1　k ＞ 0：每一支上，y 隨 x 增大而減小',
    '2　k ＜ 0：每一支上，y 隨 x 增大而增大',
    '3　兩支之間關於原點對稱，但唔可以互相比大細',
  ],
});

d.closing({
  title: 'L3 完成',
  line: '下一課：知道一個點，點樣求成條式？',
  iep: '本課為調整支援（Accommodation）：年級標準不變，只調整呈現方式與練習層次。',
});

