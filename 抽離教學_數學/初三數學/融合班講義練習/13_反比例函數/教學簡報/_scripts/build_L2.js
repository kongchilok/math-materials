// build_L2.js — 初三 13 反比例函數．L2「圖像：雙曲線兩支同象限」
const path = require('path');
const { KIT, hyperbola, plotOnly } = require('./inv_draw.js');
const { Deck } = KIT;

const d = new Deck('L2　圖像：雙曲線與象限', '初三數學');

// 延續 L1 嘅 12 粒糖：同一個 k ＝ 12
// 八點密集，唔標坐標（標籤會壓住隔籬個點）——坐標喺上一頁對應表已經有
const PTS12 = [
  { x: -6, y: -2 }, { x: -4, y: -3 }, { x: -3, y: -4 }, { x: -2, y: -6 },
  { x: 2, y: 6 }, { x: 3, y: 4 }, { x: 4, y: 3 }, { x: 6, y: 2 },
];

d.cover({
  title: '雙曲線\n係咩樣？',
  subtitle: 'L2　反比例函數的圖像',
  hook: '把 y ＝ 12/x 畫出嚟',
});

d.agenda({
  steps: [
    'x 可唔可以係負數？',
    '填表 → 描點 → 連線',
    '睇 k 嘅正負，判象限',
    '揀一層，自己做做看',
  ],
  note: '今日主要係「畫」同「睇」，唔使計難嘅嘢。',
});

// ── 引入：把 x 擴到負數 ──────────────────────────────
d.problem({
  title: '上一課淨係填正數',
  question: 'x 可唔可以係負數？',
  sub: 'x ＝ −2　→　y ＝ 12/(−2) ＝ −6\nx ＝ −3　→　y ＝ 12/(−3) ＝ −4',
  caption: '負數完全可以。唯獨 x ＝ 0 唔得——0 唔可以做分母。',
  badge: '一齊填：x ＝ −6 嘅時候，y 係幾多？',
});

d.tableSlide({
  title: '完整對應表：y ＝ 12/x',
  headers: ['x', '−6', '−3', '−2', '2', '3', '6'],
  rows: [
    ['y ＝ 12/x', '−2', '−4', '−6', '6', '4', '2'],
    ['x × y', '12', '12', '12', '12', '12', '12'],
  ],
  colW: [3.1, 1.5, 1.5, 1.5, 1.5, 1.5, 1.5],
  badge: '下一頁：一齊描點',
});

// ── CRA 表徵：描點 → 連線 ────────────────────────────
d.figure({
  title: '先描點',
  draw: plotOnly({ pts: PTS12 }),
  caption: '八個點，自然分成兩堆',
  side: ['右上一堆：', 'x、y 都係正數。', '', '左下一堆：', 'x、y 都係負數。'],
});

d.figure({
  title: '再連線',
  draw: hyperbola(12, { pts: PTS12 }),
  caption: 'y ＝ 12/x 的圖像：雙曲線，有兩支',
  side: ['連埋就係雙曲線。', '', '兩支各自一條，', '中間斷開，', '唔會駁埋一齊。'],
});

d.figure({
  title: '如果 k 變負數呢？',
  draw: hyperbola(-12, {
    pts: [{ x: -3, y: 4, label: '(−3, 4)' }, { x: -6, y: 2 }, { x: 3, y: -4, label: '(3, −4)' }, { x: 6, y: -2 }],
  }),
  caption: 'y ＝ −12/x：兩支跑咗去第二、四象限',
  side: ['k 由 12 變成 −12，', '', '兩支就由', '一、三象限', '搬咗去', '二、四象限。'],
});

d.compare2({
  title: '睇 k 嘅正負，就知喺邊',
  left:  { head: 'k ＞ 0', lines: ['例：y ＝ 12/x', '', '兩支喺', '第一、三象限', '', '（右上 ＋ 左下）'] },
  right: { head: 'k ＜ 0', lines: ['例：y ＝ −12/x', '', '兩支喺', '第二、四象限', '', '（左上 ＋ 右下）'] },
  note: '唔使畫圖都判斷到——淨係睇 k 前面有冇負號。',
});

// ── 迷思澄清：唔掂原點、唔掂坐標軸 ──────────────────
d.problem({
  title: '會唔會掂到原點？',
  question: '雙曲線會唔會經過原點 (0, 0)？',
  sub: 'x ＝ 0　→　分母係 0，計唔到。\ny ＝ 0　→　12/x 永遠唔會等於 0。',
  caption: '所以圖像唔經過原點，亦都唔會掂到兩條坐標軸——越行越近，但永遠唔掂。',
});

d.scaffold4({
  title: '睇圖四步',
  steps: [
    '搵出 k：分數線上面嗰個數',
    'k ＞ 0：兩支喺第一、三象限',
    'k ＜ 0：兩支喺第二、四象限',
    '記住：兩支都唔會掂坐標軸',
  ],
  note: '呢四步同 L1 嘅判斷步驟接得上：先搵 k，再判象限。',
  badge: '下一頁：自己揀一層做',
});

d.layered({
  cols: [
    { stars: '★☆☆', head: '練習 A',
      lines: ['y ＝ 6/x', '(1) k ＝ ？', '(2) 喺第幾象限？', '', 'y ＝ −6/x 呢？', '(1) k ＝ ？', '(2) 喺第幾象限？'] },
    { stars: '★★☆', head: '練習 B',
      lines: ['y ＝ 8/x', '', 'x ＝ 2　→　y ＝ ？', 'x ＝ −4　→　y ＝ ？', '', '再講出兩支', '喺邊兩個象限。'] },
    { stars: '★★★', head: '練習 C',
      lines: ['y ＝ k/x 嘅圖像', '有一支經過 (−3, 2)。', '', '(1) k ＝ ？', '(2) 兩支喺邊兩個', '　　象限？'] },
  ],
  note: '做完一層想試上一層，隨時可以。',
});

d.summary({
  takeaway: 'k ＞ 0 喺一、三象限；k ＜ 0 喺二、四象限',
  lines: [
    '1　圖像叫雙曲線，有兩支',
    '2　睇 k 嘅正負，就知喺邊兩個象限',
    '3　永遠唔掂原點，亦唔掂坐標軸',
  ],
});

d.closing({
  title: 'L2 完成',
  line: '下一課：喺同一支上面，y 係點樣變？',
  iep: '本課為調整支援（Accommodation）：年級標準不變，只調整呈現方式與練習層次。',
});

d.save(path.join(__dirname, '..', '簡報_L2_反比例函數的圖像.pptx'))
  .then((f) => console.log('OK', f));
