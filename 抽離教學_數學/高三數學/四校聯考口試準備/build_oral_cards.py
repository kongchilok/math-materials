_DERIVE_NOTE = '指著下面的板書由上而下逐行講，每行講出右邊「這一步在做什麼」。講完最後一行說：'


_DERIVE_NOTE_STU = '指著你自己的板書由上而下逐行講，每行講出右邊「這一步要做什麼」。講完最後一行說：'
_CLOZE = re.compile(r'⟦(.*?)⟧')


def _blank_len(ans):
    """空格長度只分三級（不按字數精確給，免得空格長短洩答案）；手寫字比印刷字大，寧長勿短。"""
    n = len(re.sub(r'frac\(|[{}()]', '', ans))
    return 4 if n <= 3 else (7 if n <= 8 else 10)


def cloze(text, student):
    """⟦…⟧：教師答案版去掉括號照印；學生版換成底線空格。"""
    if isinstance(text, (list, tuple)):
        return [cloze(t, student) for t in text]
    if not student:
        return _CLOZE.sub(lambda m: m.group(1), text)
    return _CLOZE.sub(lambda m: '＿' * _blank_len(m.group(1)), text)


def talk3plus1(t, student=False):
    """talk = dict(審題=…, 思路=…, 推導=最後一句（含對照選項）, 總結=…)；易錯點直接寫進講稿講出口，不另加 ※。
    學生版：推導只留「對照選項，答案是＿＿」——算式和結果在學生自己的板書上。"""
    if student:
        letter = re.search(r'答案是 ([A-E])', t['推導']).group(1)
        derive = cloze(f'對照選項，答案是 ⟦{letter}⟧。', True)
        return [('審題', cloze(t['審題'], True)),
                ('思路', cloze(t['思路'], True)),
                ('推導', derive, None, _DERIVE_NOTE_STU),
                ('總結', cloze(t['總結'], True))]
    return [('審題', cloze(t['審題'], False)),
            ('思路', cloze(t['思路'], False)),
            ('推導', t['推導'], None, _DERIVE_NOTE),
            ('總結', cloze(t['總結'], False))]


