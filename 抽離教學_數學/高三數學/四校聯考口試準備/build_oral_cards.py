def board_blank(hints):
    """學生版板書：左欄全空（學生課前自己寫），右欄只印「這一步要做什麼」，末列作答。"""
    wl = int(W * 0.64)
    rows = [{'hdr': True, 'cells': [
        {'p': [para('算式（自己寫）', bold=True, sz=22, spacing=False)], 'shd': GREY_FILL},
        {'p': [para('這一步要做什麼', bold=True, sz=22, spacing=False)], 'shd': GREY_FILL}]}]
    for h in hints:
        rows.append({'cells': [{'p': [blank()]},
                               {'p': [para(h, sz=21, spacing=False)], 'va': 'center'}],
                     'h': BOARD_ROW_H})
    rows.append({'cells': [{'p': [para('∴ ＿＿＿＿＿＿＿＿＿＿，選（　　）', bold=True, spacing=False)],
                            'va': 'center'},
                           {'p': [para('作答', sz=21, spacing=False)], 'va': 'center'}],
                 'h': BOARD_ROW_H})
    return _tbl(rows, [wl, W - wl])


