def build(key='2021', teacher=False):
    S = SETS[key]
    student = S.get('student') and not teacher
    kind = '口試講解卡（教師答案版）' if student and S.get('answer_suffix') else '口試講解卡'
    P = [masthead('高三數學' if student else SUBJECT, S['unit'], kind)]
    if S.get('talk'):
        # 練習階段不用 ①②③：①–④ 已是講解四步的編號（記憶 prompt_cards_must_match_upstream_handout）
        P.append(shaded_box('講解四步（老師的 3+1 步驟）：審題 → 思路 → 推導 → 總結，四步都要講。'
                            '　怎樣練習：第一輪照讀講稿 → 第二輪遮住講稿，只看板書講 → 第三輪只看題目講',
                            sz=22))
    else:
        P.append(shaded_box('怎樣練習：① 照讀講稿，手指著對應的算式　→　② 遮住講稿，只看算式講'
                            '　→　③ 只看題目講', sz=22))
    for i, src in enumerate(S['srcs'], 1):
        c = BY_SRC[src]
        P += card(i, c['src'], c['title'], c['body'], c['opts'], c['steps'], c['rows'],
                  c['qas'], c['cue'], first=(i == 1),
                  col_frac=c.get('col_frac'), why_pct=c.get('why_pct', 0.34),
                  talk=TALK[src] if S.get('talk') else None)
    if student:
        return save(P, S['base'] + S.get('answer_suffix', ''))
    P += [x.replace('w:line="360" w:lineRule="auto" w:after="80"',
                    'w:line="276" w:lineRule="auto" w:after="40"') for x in teacher_notes(
        'D6 明確教學三階段（I do – We do – You do＋放聲思考）',
        ('D2 手順卡',),
        reason=('口試要求學生「講出解題推理」，正是 D6 放聲思考的引號句；'
                'D2 把每題拆成' + ('科任《課堂口試講解 3+1 大步驟》的「審題 → 思路 → 推導 → 總結」'
                                  if S.get('talk') else '「說考點 → 拆題 → 講計算 → 講答案」') +
                '四個固定動作，讓學生每題用同一個框架開口，減輕臨場組織語言的負荷。'),
        density='抽離小班（高三甲融合生 2 人）',
        fading=('第 1 堂：照讀講稿（對稿）→ 第 2 堂：遮住講稿，只看算式講'
                '（算式欄即 D2 的「只含關鍵詞清單」）→ 第 3 堂：只看題目講，再模擬抽籤口試 → '
                '正式口試：不帶卡（脫稿）。'),
        flows=('F5 課前流程預告（每堂開始先講今天練哪幾張卡）',
               'F4 過程導向回饋（針對' + ('審題／思路／推導／總結' if S.get('talk') else '手順 ①–④')
               + ' 哪一步卡住）'),
        extra=S['extra'],
    )]
    base = S['base'] if not S.get('student') else '教師版_' + S['base']
    return save(P, base)


def build_student(key='2021'):
    """學生版：板書全空、講稿關鍵詞填空（2026-10-20）。"""
    S = SETS[key]
    P = [masthead('高三數學', S['unit'], '口試講解卡（學生版）'), student_info_row()]
    P.append(shaded_box('怎樣用：課前——自己做「一、板書」。上堂——聽老師講解，用另一種顏色的筆改正板書，'
                        '並填好「二、講稿」的空格。之後——照讀講稿 → 只看板書講 → 只看題目講。'
                        '講解四步：審題 → 思路 → 推導 → 總結，四步都要講。', sz=22))
    for i, src in enumerate(S['srcs'], 1):
        P += student_card(i, BY_SRC[src], TALK[src], HINT[src], first=(i == 1))
    return save(P, S['base'] + '_學生版')


def build_sentence_card():
    P = [masthead('高三數學', '課堂口試講解', '口試句型卡'), sentence_card()]
    return save(P, '口試講解卡_通用3+1句型卡')


def save(P, base):
    out = os.path.join(OUT, base + '.docx')
    build_docx([tighten(x) for x in P], out, footer_text=FOOT)
    print('OK', out)


