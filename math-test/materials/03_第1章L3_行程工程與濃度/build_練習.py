def _esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


_TEX_MAP = {"<=": r"\le", ">=": r"\ge", "!=": r"\ne", "->": r"\to", "+-": r"\pm",
            "*": r"\times"}


def _tex(m):
    import re
    m = m.strip()
    body = m
    for _ in range(6):
        new = re.sub(r"frac\(([^(),]+),([^(),]+)\)", r"\\frac{\1}{\2}", body)
        if new == body:
            break
        body = new
    for k, v in _TEX_MAP.items():
        body = body.replace(k, " " + v + " ")
    # 分子分母都要吃小數點——寫成 (\d+)/(\d+) 會把 60/0.12 讀成 60/0 再多出一個 .12，
    # 與 omml_core 的 _NUM_RE（本來就吃小數）不一致，docx 對而 HTML 錯（2026-07-27 實錄）。
    body = re.sub(r"(?<![\\{\w.])(\d+(?:\.\d+)?)/(\d+(?:\.\d+)?)(?![}\w.])",
                  r"\\frac{\1}{\2}", body)
    body = body.replace("%", r"\%")
    return r"\(%s\)" % body


def _h(s):
    import re
    out, i = [], 0
    for m in re.finditer(r"\{([^{}]*(?:\{[^{}]*\}[^{}]*)*)\}", s):
        out.append(_esc(s[i:m.start()]))
        out.append(_tex(m.group(1)))
        i = m.end()
    out.append(_esc(s[i:]))
    return "".join(out)


def _cell(lines):
    return "".join("<div>%s</div>" % _h(t) for t in lines)


def _lines(n):
    return '<div class="write-lines">' + '<div class="line"></div>' * n + "</div>"


