db.add_flow_preview(prs, FOOTER, "今天要做的四件事", [
    "認五張題型卡：什麼時候翻我",
    "五個範例：雞兔、年齡、時鐘、數位、幾何",
    "抓住兩個最容易錯的步驟",
    "老師陪你做練習A，你自己做B、C",
])

# 3 問題引入
db.add_question_intro(prs, FOOTER, "先想一想",
    "籠裡關住雞和兔，共 12 個頭、40 隻腳，\n兔有多少隻？",
    ["6 隻", "8 隻", "10 隻"],
    "兩種動物、兩個總量——等一下用兩條式來解。")

# 4 CRA①：雞兔同籠，relabel 成「觸發語／設定式／代入檢核」，呼應 D7 提示卡結構
db.add_cra(prs, FOOTER, "範例：提示卡完整走一次（雞兔同籠）",
    concrete={"label": "①觸發語", "desc": "題目給出\n兩種東西的\n總個數（頭）\n同時給出\n另一總量\n（腳）\n\n翻《雞兔卡》"},
    representational={"label": "②設定式", "desc": "設兔 x 隻\n雞 y 隻\n\n① x+y=12\n（頭數）\n\n② 4x+2y=40\n（腳數）"},
    abstract={"label": "③代入檢核", "desc": "解得 x=8\ny=12-8=4\n\n頭：8+4=12 ✓\n腳：8×4+4×2\n=40 ✓\n\n兔8隻、雞4隻"})

# 5 步驟卡：五種題型的觸發語精簡對照表
db.add_step_card(prs, FOOTER, "五種題型，一眼辨認（觸發語）", [
    "雞兔同籠：給兩種東西的總個數＋另一總量",
    "年齡：出現幾年前／幾年後／幾倍／年齡和差",
    "時鐘：出現時針、分針、夾角，或快慢鐘",
    "數位：出現個位、十位、兩位數、數字對調",
    "幾何：出現周長、面積、表面積、體積、稜長",
], note="讀完題目，先在這五行裡找出對得上的那一句。")

# 6 過渡頁1
db.add_transition(prs, "接下來，看兩個\n最容易錯的步驟", FOOTER)

# 7 迷思澄清：時鐘／年齡／數位，三個真實高頻錯法（呼應 D14）
db.add_misconception(prs, FOOTER, "三個最常見的錯法", [
    {"wrong": "時針停在整點，3點算90°", "right": "時針每分鐘走0.5°，應為105°"},
    {"wrong": "只把其中一人的年齡減16", "right": "兩人年齡同時要減16年"},
    {"wrong": "十位個位數字直接相加／相乘", "right": "兩位數要寫成10a＋b才列式"},
])

# 8 2x2 四格鷹架：年齡（16年前3倍、現在2倍），對應解題四動作
db.add_scaffold_2x2(prs, FOOTER, "範例：解題四動作完整走一次（年齡）",
    problem="【範例】16年前父親年齡是阿達的3倍，\n現在是2倍。阿達今年幾歲？",
    what="阿達今年的\n年齡是多少？",
    given="現在：父親＝阿達的2倍\n16年前：父親＝阿達的3倍",
    strategy="設阿達今年 x 歲\n父親今年 2x 歲\n16年前：兩人都減16\n2x-16=3(x-16)",
    check="解得 x=32（歲）\n父親 64 歲\n年齡差：64-32=32\n16年前：48-16=32 ✓")

# 9 步驟卡：自己動手時的四個動作
