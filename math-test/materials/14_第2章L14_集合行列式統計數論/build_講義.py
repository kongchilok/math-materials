def _step_html(card):
    rows = ['<tr><th colspan="2">%s</th></tr>' % _h(card["title"])]
    rows.append('<tr><td colspan="2" style="font-weight:400">什麼時候用：%s</td></tr>'
                % _h(card["trigger"]))
    for i, (act, pit) in enumerate(card["steps"], 1):
        rows.append('<tr><td>%d. %s</td><td class="pitfall">※ %s</td></tr>'
                    % (i, _h(act), _h(pit)))
    return '<table class="d-tbl step-card">%s</table>' % "".join(rows)


def _tbl_html(rows, heads, cls="three-col"):
    return ('<table class="d-tbl %s"><thead><tr>%s</tr></thead><tbody>%s</tbody></table>'
            % (cls, "".join("<th>%s</th>" % _esc(h) for h in heads),
               "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % _h(c) for c in r)
                       for r in rows)))


def _kw_html(general, traps):
    rows = ["<tr><th>題目說…</th><th>就寫成…</th></tr>"]
    for k, v in general:
        rows.append("<tr><td>%s</td><td>%s</td></tr>" % (_h(k), _h(v)))
    rows.append('<tr><th colspan="2">⚠ 陷阱詞（要想一下，不能直接照字面翻）</th></tr>')
    for k, v in traps:
        rows.append("<tr><td>%s</td><td>%s</td></tr>" % (_h(k), _h(v)))
    return '<table class="d-tbl kw-table">%s</table>' % "".join(rows)


def _fig_html(svg, cap=None):
    c = '<div class="fig-cap">%s</div>' % _esc(cap) if cap else ""
    return '<div class="fig">%s%s</div>' % (svg, c)


