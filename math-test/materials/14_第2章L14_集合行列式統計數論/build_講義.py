def _esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


_TEX_MAP = {"<=": r"\le", ">=": r"\ge", "!=": r"\ne", "->": r"\to",
            "+-": r"\pm", "-+": r"\mp", "*": r"\times"}
_MAT_ENV = (("det(", "vmatrix"), ("pmat(", "pmatrix"), ("mat(", "bmatrix"))


def _split_args(s, start):
    depth, args, cur, i = 0, [], [], start
    while i < len(s):
        c = s[i]
        if c == "(":
            depth += 1
            if depth == 1:
                i += 1
                continue
        elif c == ")":
            depth -= 1
            if depth == 0:
                args.append("".join(cur))
                return args, i + 1
        elif c == "," and depth == 1:
            args.append("".join(cur))
            cur = []
            i += 1
            continue
        cur.append(c)
        i += 1
    return None, start


def _grab(s, i):
    """i 指住 '('，回傳（括號內原文, 右括號之後的索引）。"""
    depth, j = 0, i
    while j < len(s):
        if s[j] == "(":
            depth += 1
        elif s[j] == ")":
            depth -= 1
            if depth == 0:
                return s[i + 1:j], j + 1
        j += 1
    return None, i


def _split_top(s, sep):
    depth, out, cur = 0, [], []
    for c in s:
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        if c == sep and depth == 0:
            out.append("".join(cur))
            cur = []
            continue
        cur.append(c)
    out.append("".join(cur))
    return out


def _conv(s):
    out, i = [], 0
    while i < len(s):
        # 行列式／矩陣：{det(a,b;c,d)} → \begin{vmatrix}a & b \\ c & d\end{vmatrix}
        hit = False
        for kw, env in _MAT_ENV:
            if s.startswith(kw, i):
                inner, end = _grab(s, i + len(kw) - 1)
                if inner is not None:
                    rows = [" & ".join(_conv(c.strip())
                                       for c in _split_top(r, ","))
                            for r in _split_top(inner, ";")]
                    out.append(r"\begin{%s}%s\end{%s}"
                               % (env, r" \\ ".join(rows), env))
                    i = end
                    hit = True
                    break
        if hit:
            continue
        if s.startswith("frac(", i):
            args, end = _split_args(s, i + 4)
            if args and len(args) == 2:
                out.append("\\frac{%s}{%s}" % (_conv(args[0]), _conv(args[1])))
                i = end
                continue
        if s.startswith("sqrt(", i):
            args, end = _split_args(s, i + 4)
            if args and len(args) == 1:
                out.append("\\sqrt{%s}" % _conv(args[0]))
                i = end
                continue
        out.append(s[i])
        i += 1
    return "".join(out)


def _tex(m):
    import re
    body = m.strip()
    body = re.sub(r"fn\((\w+)\)", r"\\\1 ", body)
    body = _conv(body)
    body = re.sub(r"\bpi\b", r"\\pi ", body)
    body = re.sub(r"\^\(([^()]*)\)", r"^{(\1)}", body)
    body = re.sub(r"_\(([^()]*)\)", r"_{(\1)}", body)
    body = re.sub(r"\^(\w{2,})", r"^{\1}", body)
    body = re.sub(r"_(\w{2,})", r"_{\1}", body)
    for k, v in _TEX_MAP.items():
        body = body.replace(k, " " + v + " ")
    body = body.replace("<", r" \lt ").replace(">", r" \gt ")
    body = re.sub(r"(?<![\\{\w.!])(\d+(?:\.\d+)?)/(\d+(?:\.\d+)?)(?![}\w.])",
                  r"\\frac{\1}{\2}", body)
    body = body.replace("%", r"\%")
    body = body.replace("°", r"^{\circ}")
    body = body.replace("÷", r" \div ").replace("≈", r" \approx ")
    body = body.replace("∪", r" \cup ").replace("∩", r" \cap ")
    # 中文要包 \text{}，否則 MathJax 逐字當變數排斜體
    body = re.sub(r"[\u4e00-\u9fff]+", lambda x: r"\text{%s}" % x.group(0), body)
    return r"\(%s\)" % body


def _h(s):
    import re
    s = s.replace("**", "")
    out, i = [], 0
    for m in re.finditer(r"\{([^{}]*(?:\{[^{}]*\}[^{}]*)*)\}", s):
        out.append(_esc(s[i:m.start()]))
        out.append(_tex(m.group(1)))
        i = m.end()
    out.append(_esc(s[i:]))
    return "".join(out)


