def _esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


_TEX_MAP = {"<=": r"\le", ">=": r"\ge", "!=": r"\ne", "->": r"\to",
            "+-": r"\pm", "-+": r"\mp", "*": r"\times"}


def _split_args(s, start):
    depth, args, cur, i = 0, [], [], start
    while i < len(s):
        c = s[i]
        if c == "(":
            depth += 1
            if depth == 1:
                i += 1
                continue
        elif c == ")":
            depth -= 1
            if depth == 0:
                args.append("".join(cur))
                return args, i + 1
        elif c == "," and depth == 1:
            args.append("".join(cur))
            cur = []
            i += 1
            continue
        cur.append(c)
        i += 1
    return None, start


def _conv(s):
    out, i = [], 0
    while i < len(s):
        if s.startswith("frac(", i):
            args, end = _split_args(s, i + 4)
            if args and len(args) == 2:
                out.append("\\frac{%s}{%s}" % (_conv(args[0]), _conv(args[1])))
                i = end
                continue
        if s.startswith("sqrt(", i):
            args, end = _split_args(s, i + 4)
            if args and len(args) == 1:
                out.append("\\sqrt{%s}" % _conv(args[0]))
                i = end
                continue
        out.append(s[i])
        i += 1
    return "".join(out)


def _tex(m):
    import re
    body = m.strip()
    body = re.sub(r"fn\((\w+)\)", r"\\\1 ", body)
    body = _conv(body)
    body = re.sub(r"\bpi\b", r"\\pi ", body)
    body = re.sub(r"\^\(([^()]*)\)", r"^{(\1)}", body)
    body = re.sub(r"_\(([^()]*)\)", r"_{(\1)}", body)
    body = re.sub(r"\^(\w{2,})", r"^{\1}", body)
    body = re.sub(r"_(\w{2,})", r"_{\1}", body)
    for k, v in _TEX_MAP.items():
        body = body.replace(k, " " + v + " ")
    body = body.replace("<", r" \lt ").replace(">", r" \gt ")
    body = re.sub(r"(?<![\\{\w.!])(\d+(?:\.\d+)?)/(\d+(?:\.\d+)?)(?![}\w.])",
                  r"\\frac{\1}{\2}", body)
    body = body.replace("%", r"\%")
    body = body.replace("°", r"^{\circ}")
    # 中文（末項／首項）要包 \text{}，否則 MathJax 逐字當變數排斜體
    body = re.sub(r"[\u4e00-\u9fff]+", lambda x: r"\text{%s}" % x.group(0), body)
    return r"\(%s\)" % body


def _h(s):
    import re
    s = s.replace("**", "")
    out, i = [], 0
    for m in re.finditer(r"\{([^{}]*(?:\{[^{}]*\}[^{}]*)*)\}", s):
        out.append(_esc(s[i:m.start()]))
        out.append(_tex(m.group(1)))
        i = m.end()
    out.append(_esc(s[i:]))
    return "".join(out)


def _frayer_html(title, cells):
    heads = ("① 定義（用自己的話）", "② 公式", "③ 是的例", "④ 不是的例")
    body = ""
    for i in (0, 2):
        body += ("<tr><td><div class=\"fh\">%s</div>%s</td>"
                 "<td><div class=\"fh\">%s</div>%s</td></tr>"
                 % (_esc(heads[i]), _h(cells[i]),
                    _esc(heads[i + 1]), _h(cells[i + 1])))
    return ('<table class="d-tbl frayer"><tr><th colspan="2">%s</th></tr>%s</table>'
            % (_esc(title), body))


def _step_html(card):
    rows = ['<tr><th colspan="2">%s</th></tr>' % _h(card["title"])]
    rows.append('<tr><td colspan="2" style="font-weight:400">什麼時候用：%s</td></tr>'
                % _h(card["trigger"]))
    for i, (act, pit) in enumerate(card["steps"], 1):
        rows.append('<tr><td>%d. %s</td><td class="pitfall">※ %s</td></tr>'
                    % (i, _h(act), _h(pit)))
    return '<table class="d-tbl step-card">%s</table>' % "".join(rows)


