def frayer_docx(title, cells):
    """弗雷爾概念模型（D13）：一個標題列 ＋ 2×2 四象限。
    cells 順序固定為（定義, 公式, 是的例, 不是的例）——四格的位置不要換，
    學生記的是「左上是定義、右下是非例」這個空間位置。"""
    half = _PAGE_CONTENT_WIDTH // 2
    widths = [half, _PAGE_CONTENT_WIDTH - half]
    heads = ("① 定義（用自己的話）", "② 公式", "③ 是的例", "④ 不是的例")
    rows = [{"cells": [{"p": [para(title, bold=True, sz=HEADING_SZ)],
                        "span": 2, "shd": GREY_FILL}]}]
    for i in (0, 2):
        rows.append({"cells": [
            {"p": [para(heads[i], bold=True, sz=21, shd=GREY_FILL),
                   para(cells[i], sz=21)]},
            {"p": [para(heads[i + 1], bold=True, sz=21, shd=GREY_FILL),
                   para(cells[i + 1], sz=21)]}]})
    return _tbl(rows, widths)


def grid_table(rows, headers, h=460):
    n = len(headers)
    w = _PAGE_CONTENT_WIDTH // n
    widths = [w] * (n - 1) + [_PAGE_CONTENT_WIDTH - w * (n - 1)]
    out = [{"hdr": True,
            "cells": [{"p": [para(x, bold=True, sz=22, jc="center")],
                       "shd": GREY_FILL} for x in headers]}]
    for r in rows:
        out.append({"cells": [{"p": [para(c, jc="center")]} for c in r], "h": h})
    return _tbl(out, widths)


